class FrontTests(unittest.TestCase):
    def test_from_this_computer(self):
        ok = {"Host": "localhost:8080"}
        self.assertTrue(front.from_this_computer(ok, "127.0.0.1", public=False))
        self.assertTrue(front.from_this_computer({"Host": "127.0.0.1:8080"}, "::1", public=False))
        self.assertTrue(front.from_this_computer({"Host": "ytlogintest.localhost:18380"}, "127.0.0.1", False))
        self.assertTrue(front.from_this_computer({"Host": "[::1]:8080"}, "::ffff:127.0.0.1", False))
        self.assertFalse(front.from_this_computer(ok, "127.0.0.1", public=True), "tunnel port")
        self.assertFalse(front.from_this_computer(ok, "192.168.1.20", public=False), "another device on the LAN")
        self.assertFalse(front.from_this_computer({"Host": "192.168.1.5:8080"}, "127.0.0.1", False))
        self.assertFalse(front.from_this_computer({"Host": "evil.example"}, "127.0.0.1", False), "DNS rebinding")
        self.assertFalse(front.from_this_computer({"Host": "localhost.evil.example"}, "127.0.0.1", False))
        self.assertFalse(front.from_this_computer({}, "127.0.0.1", False))
        for name in ("X-Forwarded-For", "Forwarded", "CF-Connecting-IP", "X-Real-IP", "Via", "X-Forwarded-Host"):
            self.assertFalse(front.from_this_computer(dict(ok, **{name: "203.0.113.9"}), "127.0.0.1", False),
                             f"a local tunnel or proxy ({name}) is not this computer")
        self.assertIn("x-front-local", front._DROPPED_IN, "a client cannot claim it")


class _Handler:
    """Just enough of web.py's handler for ytsettings / ytaccount."""

    def __init__(self, caller, body=None, peer="127.0.0.1", headers=None, query=None):
        self.caller = caller
        raw = json.dumps(body).encode() if body is not None else b""
        self.headers = {"Content-Length": str(len(raw)), **(headers or {})}
        self.rfile = io.BytesIO(raw)
        self.client_address = (peer, 50000)
        self.answers = []
        self.close_connection = False
        self.query = query or {}

    def _caller(self):
        return self.caller

    def _query(self):
        return self.query

    def _ip(self):
        return self.client_address[0]

    def _json(self, data, code=200, headers=None):
        self.answers.append((code, data))

    def _not_found(self):
        self.answers.append((404, None))


