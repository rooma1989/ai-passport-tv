class ReadTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dest = Path(self.tmp.name) / "youtube" / "cookies.txt"
        self.calls = []

    def tearDown(self):
        self.tmp.cleanup()

    def fake(self, jar: str | None, stderr: str = "", code: int = 2, raise_=None):
        def run(args, timeout):
            self.calls.append(args)
            out = Path(args[args.index("--cookies") + 1])
            self.assertEqual(stat.S_IMODE(out.parent.stat().st_mode) & 0o077, 0, "temp folder is private")
            if raise_ is not None:
                raise raise_
            if jar is not None:
                out.write_text(jar, encoding="utf-8")
            return code, stderr
        return run

    def leftovers(self):
        return [p.name for p in self.dest.parent.iterdir() if p.name.startswith(ytbrowser.TEMP_PREFIX)]

    def test_success_keeps_only_youtube_and_cleans_up(self):
        stale = self.dest.parent / (ytbrowser.TEMP_PREFIX + "old")
        stale.mkdir(parents=True)
        (stale / "all.txt").write_text(FULL_JAR)
        result = ytbrowser.read("/bin/yt-dlp", "chrome:/x/Default", "chrome", self.dest,
                                run=self.fake(FULL_JAR, "ERROR: You must provide at least one URL."))
        self.assertEqual((result["count"], result["login"]), (3, True))
        self.assertNotIn(SECRET, json.dumps(result))
        stored = self.dest.read_text()
        self.assertNotIn("bank.example", stored)
        self.assertIn("LOGIN_INFO", stored)
        if os.name == "posix":
            self.assertEqual(stat.S_IMODE(self.dest.stat().st_mode), 0o600)
        self.assertEqual(self.leftovers(), [], "temp files (with every site's cookies) are gone, stale ones too")

    def test_failure_kind_for_the_log(self):
        with self.assertRaises(ytbrowser.BrowserError) as caught:
            ytbrowser.read("/bin/yt-dlp", "safari", "safari", self.dest,
                           run=self.fake(None, f"ERROR: [Errno 1] Operation not permitted: '{SECRET}'", code=1))
        self.assertEqual(caught.exception.kind, "no-permission")

    def test_failures_keep_the_old_file_and_clean_up(self):
        self.dest.parent.mkdir(parents=True)
        self.dest.write_text("old")
        for run, expected in (
            (self.fake(None, "ERROR: [Errno 1] Operation not permitted: '/x'", code=1), "完全磁盘访问权限"),
            (self.fake(GUEST_JAR), "没有登录"),
            (self.fake("# Netscape HTTP Cookie File\n.bank.example\tTRUE\t/\tTRUE\t0\ts\tv\n"), "没有 YouTube"),
            (self.fake(None, raise_=subprocess.TimeoutExpired("yt-dlp", 1)), "允许"),
            (self.fake(None, raise_=FileNotFoundError("yt-dlp")), "安装"),
        ):
            with self.assertRaises(ytbrowser.BrowserError) as caught:
                ytbrowser.read("/bin/yt-dlp", "safari", "safari", self.dest, run=run)
            self.assertIn(expected, str(caught.exception))
            self.assertNotIn(SECRET, str(caught.exception))
            self.assertEqual(self.dest.read_text(), "old", "a failed read never replaces the cookies")
            self.assertEqual(self.leftovers(), [])

    def test_the_child_runs_with_a_private_umask(self):
        with mock.patch("subprocess.run") as run:
            run.return_value = subprocess.CompletedProcess([], 2, "", "")
            ytbrowser._run(["yt-dlp"], 5)
        kwargs = run.call_args.kwargs
        if os.name == "posix":
            self.assertEqual(kwargs["umask"], 0o077)
        self.assertEqual(kwargs["stdin"], subprocess.DEVNULL)


