// Writes the standalone brand SVGs in this folder from the single source in
// ../index.html (the code between BRAND-ICONS-START and BRAND-ICONS-END).
// Run from anywhere:  node docs/design/media-center/brand/export.mjs
// Edit the builder in index.html, then re-run; do not hand-edit the outputs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, "..", "index.html"), "utf8");
const a = html.indexOf("/* BRAND-ICONS-START"), b = html.indexOf("/* BRAND-ICONS-END */");
if (a < 0 || b < 0) throw new Error("brand builder markers not found in index.html");
const { ICON_VARIANTS, iconSVG, traySVG, wordmarkSVG } = new Function(`${html.slice(a, b)}; return { ICON_VARIANTS, iconSVG, traySVG, wordmarkSVG };`)();

const NAME = "RooTV", NAME_ZH = "小鼠电视"; // the Chinese name, kept as escapes so this file stays ASCII
const head = what => `<!-- ${NAME} ${what}. Generated by export.mjs from ../index.html; do not edit by hand. -->\n`;
const out = (file, svg) => { writeFileSync(join(here, file), svg + "\n"); console.log("wrote", file); };

for (const [v, V] of Object.entries(ICON_VARIANTS)) {
  out(`icon-${v}.svg`, head(`app icon, candidate ${v.toUpperCase()} (1024 master, use for 64 px and up)`) + iconSVG(v, { size: 1024, uid: "m", label: NAME }));
  out(`icon-${v}-small.svg`, head(`app icon, candidate ${v.toUpperCase()}, simplified for 16-32 px`) + iconSVG(v, { size: 1024, small: true, uid: "s", label: NAME }));
  // macOS menu bar template image: black + alpha only; the system recolours it.
  out(`tray-${v}.svg`, head(`tray / menu bar template icon, candidate ${v.toUpperCase()} (black on transparent)`) + traySVG(v, { size: 32, color: "#000", uid: "t" }));
}
out("wordmark-rootv.svg", head("wordmark for light backgrounds") + wordmarkSVG({ h: 104, roo: "#111113" }));
out("wordmark-rootv-white.svg", head("wordmark for dark backgrounds") + wordmarkSVG({ h: 104, roo: "#f5f5f7" }));
// Stacked lock-up: wordmark over the Chinese name. The Chinese name is live
// text in the system font; outline it in a vector editor before production use.
const lockup = roo => {
  const wm = wordmarkSVG({ h: 104, roo }).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 322 170" width="322" height="170" role="img" aria-label="${NAME} ${NAME_ZH}">${wm}
<text x="161" y="158" text-anchor="middle" font-family="PingFang SC, Hiragino Sans GB, Microsoft YaHei, Noto Sans CJK SC, sans-serif" font-size="40" font-weight="700" letter-spacing="10" fill="${roo}" fill-opacity=".72">${NAME_ZH}</text></svg>`;
};
out("wordmark-lockup-zh.svg", head("wordmark + Chinese name lock-up, light backgrounds (Chinese is live text)") + lockup("#111113"));
out("wordmark-lockup-zh-white.svg", head("wordmark + Chinese name lock-up, dark backgrounds (Chinese is live text)") + lockup("#f5f5f7"));
