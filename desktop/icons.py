"""Tray icons: RooTV's "TV with mouse ears" (brand icon B).

The images are files in desktop/assets/, generated by tools/make_icons.py from
docs/design/media-center/brand/tray-b.svg (macOS) and icon-b-small.svg
(Windows, Linux):

    tray-template-<kind>.png, tray-template-<kind>@2x.png   18/36 px, black + alpha
    tray-<kind>-16.png, tray-<kind>-32.png                  in colour

<kind> is "idle", "watching" (the screen lights up) or "problem" (an amber
badge). On macOS the image is a template: the menu bar recolours it for light
and dark mode, and `mac_image` gives AppKit both pixel densities. Windows and
Linux show the coloured app icon, readable on light and dark taskbars alike.

Should a file be missing (a broken bundle), `draw` falls back to drawing the
same outline with Pillow, so the tray never fails over an icon.
"""

from __future__ import annotations

from pathlib import Path

KINDS = ("idle", "watching", "problem")
ASSETS = Path(__file__).resolve().parent / "assets"
TEMPLATE_PT = 18

BLACK = (0, 0, 0, 255)
CLEAR = (0, 0, 0, 0)
NIGHT = (32, 38, 74, 255)
EAR = (220, 214, 230, 255)
LIT = (93, 112, 214, 255)
AMBER = (255, 181, 71, 255)


def file_for(kind: str, template: bool, retina: bool = True, size: int = 32) -> Path:
    if kind not in KINDS:
        kind = "idle"
    if template:
        return ASSETS / f"tray-template-{kind}{'@2x' if retina else ''}.png"
    return ASSETS / f"tray-{kind}-{16 if size <= 16 else 32}.png"


def draw(kind: str, template: bool, size: int | None = None):
    """A Pillow image for pystray: the @2x template on macOS, 32 px colour elsewhere."""
    from PIL import Image
    path = file_for(kind, template)
    try:
        image = Image.open(path)
        image.load()
        image = image.convert("RGBA")
    except OSError:
        image = _drawn(kind, template, 64)
    if size and image.size != (size, size):
        image = image.resize((size, size), Image.LANCZOS)
    return image


def mac_image(kind: str):
    """An NSImage of TEMPLATE_PT points with the @1x and @2x files as its
    representations, marked as a template. None when AppKit or a file is missing."""
    try:
        import AppKit
        import Foundation
    except ImportError:
        return None
    image = AppKit.NSImage.alloc().initWithSize_((TEMPLATE_PT, TEMPLATE_PT))
    for retina in (False, True):
        try:
            data = file_for(kind, True, retina).read_bytes()
        except OSError:
            return None
        rep = AppKit.NSBitmapImageRep.imageRepWithData_(Foundation.NSData.dataWithBytes_length_(data, len(data)))
        if rep is None:
            return None
        rep.setSize_((TEMPLATE_PT, TEMPLATE_PT))
        image.addRepresentation_(rep)
    image.setTemplate_(True)
    return image


def _drawn(kind: str, template: bool, size: int = 64):
    """The fallback: tray-b.svg's shapes (32 grid) drawn with Pillow."""
    from PIL import Image, ImageDraw
    scale = 4      # draw large, then shrink: smooth edges without anti-aliasing support in ImageDraw
    s = size * scale
    u = s / 32
    image = Image.new("RGBA", (s, s), CLEAR)
    d = ImageDraw.Draw(image)
    body = BLACK if template else EAR
    screen = CLEAR if template else NIGHT
    for cx in (9, 23):
        d.ellipse([(cx - 5) * u, 3.2 * u, (cx + 5) * u, 13.2 * u], fill=body)
    d.rounded_rectangle([3 * u, 9.5 * u, 29 * u, 29 * u], radius=7 * u, fill=body)
    d.rounded_rectangle([7 * u, 13.6 * u, 25 * u, 25 * u], radius=4 * u, fill=screen)
    if kind == "watching":
        d.rounded_rectangle([9 * u, 15.6 * u, 23 * u, 23 * u], radius=2 * u, fill=BLACK if template else LIT)
    eyes = CLEAR if template and kind == "watching" else (BLACK if template else EAR)
    for cx in (12.6, 19.4):
        d.ellipse([(cx - 1.9) * u, 17.1 * u, (cx + 1.9) * u, 20.9 * u], fill=eyes)
    if kind == "problem":
        d.ellipse([19.8 * u, 19.8 * u, 32.2 * u, 32.2 * u], fill=CLEAR)
        d.ellipse([21.4 * u, 21.4 * u, 30.6 * u, 30.6 * u], fill=BLACK if template else AMBER)
    return image.resize((size, size), Image.LANCZOS)
