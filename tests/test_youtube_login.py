class FilterTests(unittest.TestCase):
    def test_only_youtube_and_google(self):
        text, count, login = ytbrowser.filter_cookies(FULL_JAR)
        kept = [line.split("\t")[0] for line in text.splitlines() if line and not line.startswith("# ")]
        self.assertEqual(sorted(kept), sorted([".youtube.com", ".youtube.com", "#HttpOnly_.youtube.com",
                                               ".google.com"]))
        self.assertEqual((count, login), (3, True))
        for gone in ("bank.example", "notyoutube.com", "evil.example", "mail.google.com", "GMAIL_AT"):
            self.assertNotIn(gone, text)
        # What is stored passes the importer's own check.
        self.assertEqual(ytlocal.parse_cookies(text)[1], 3)

    def test_guest_cookies_are_not_a_login(self):
        _, count, login = ytbrowser.filter_cookies(GUEST_JAR)
        self.assertEqual((count, login), (2, False))

    def test_too_many_cookies_are_trimmed_google_first(self):
        lines = ["# Netscape HTTP Cookie File", f".youtube.com\tTRUE\t/\tTRUE\t{FUTURE}\tLOGIN_INFO\tv"]
        lines += [f".google.com\tTRUE\t/\tTRUE\t{FUTURE}\tG{n}\t{'x' * 400}" for n in range(300)]
        text, count, login = ytbrowser.filter_cookies("\n".join(lines))
        self.assertLess(len(text.encode()), ytlocal.COOKIES_MAX)
        self.assertIn("LOGIN_INFO", text)
        self.assertEqual((count, login), (1, True))


