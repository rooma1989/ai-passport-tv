    def test_spec_only_for_listed_profiles(self):
        support = self.home / "Library" / "Application Support"
        self._chromium(support / "Google" / "Chrome")
        self._firefox(support / "Firefox")
        safari = self.home / "Safari.app"
        safari.mkdir()
        found = ytbrowser.detect("Darwin", self.home, environ={}, safari_app=safari)
        spec, chosen = ytbrowser.spec_for(found, "chrome", "Profile 2")
